const LINES_PER_PAGE = 38

/** 与 python 端一致的粗略页数估算。 */
export function estimatePages(sections) {
  let lines = 0
  for (const sec of sections) {
    if (sec.heading) lines += sec.level === 1 ? 2.2 : sec.level === 2 ? 1.8 : 1.6
    for (const p of sec.paragraphs || []) lines += String(p).length / 33 + 0.32
    lines += (sec.bullets || []).length * 0.8
    lines += (sec.steps || []).length * 0.8
    if (sec.table) lines += (sec.table.rows || []).length * 1.6 + 1.2
    if (sec.image) lines += 14
  }
  return Math.max(1, Math.round(lines / LINES_PER_PAGE) + 1)
}

/**
 * 每份文档只补「自己该有的」章节，不复制别的文档内容。
 * 每个文档有独立的 supplements 列表，跨文档不重复。
 */

/** 按功能组生成段落（不同文档用不同措辞，避免跨文档雷同）。 */
function groupParagraphs(ctx, prefix, make) {
  return groupMenus(ctx.menus).map((g) => ({
    ...h2(`${prefix}：${g.name}`),
    paragraphs: make(g),
  }))
}

function finish(sections, ctx, target = 25, supplements = []) {
  let i = 0
  while (estimatePages(sections) < target && i < supplements.length) {
    const block = supplements[i++]
    if (Array.isArray(block)) sections.push(...block)
    else sections.push(block)
  }
  return sections
}

/** 逐功能明细：只给「详细设计」和「使用说明书」用，其它文档不重复。 */
function perFunctionSections(ctx, { withSteps = true, withChecks = true } = {}) {
  const out = []
  for (const g of groupMenus(ctx.menus)) {
    out.push({ ...h2(`页面设计明细：${g.name}`), paragraphs: [`${g.name}模块各页面的设计要点如下。`] })
    for (const m of g.items) {
      const sec = {
        ...h3(m.title),
        paragraphs: [
          `页面路径：${m.route || '—'}，归属${g.name}。`,
          `页面按统一布局组织：上方为查询区，中部为数据区，底部为分页；数据范围由当前账号的角色决定。`,
          `涉及录入时按表单模型校验必填项与格式，校验不通过时在字段下方提示，已填内容保留。`,
        ],
      }
      if (withSteps) {
        sec.steps = ['从左侧菜单进入该页面；', '按业务需要填写条件或新增；', '核对后提交；', '在列表中确认结果。']
      }
      if (withChecks) {
        sec.bullets = ['必填项为空时阻止提交；', '金额与日期按格式校验；', '删除前二次确认；', '提交成功后提示并刷新列表。']
      }
      out.push(sec)
    }
  }
  return out
}

